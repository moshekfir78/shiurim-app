def taxonomy():
    t = [{"id": i, "name": n, "parent": None} for i, n in TOP]
    t += [{"id": "chag:" + i, "name": n, "parent": "chag"} for i, n, _ in CHAG]
    t += [{"id": "tanach:" + b, "name": b, "parent": "tanach"} for b in TORAH + NACH]
    t += [{"id": "gemara:" + ("נדה" if m == "נידה" else m), "name": "מסכת " + ("נדה" if m == "נידה" else m), "parent": "gemara"} for m in MAS if m != "נידה"]
    t += [{"id": "chasidut:tanya", "name": "תניא", "parent": "chasidut"}]
    return t
TANYA = w("תניא", "התניא", "ליקוטי אמרים")

def classify_topics(title, path_titles, tags, extra="", par=None):
    """title/path/tags/extra: strings used read-only. Returns sorted list of topic ids."""
    text = " ".join([title, " ".join(tags or []), extra or ""])
    path = " ".join(path_titles)
    full = text + " | " + path
    out = set()
    if par: out.add("parasha")
    for k, rx in RULES.items():
        if rx.search(full): out.add(k)
    for i, _, rx in CHAG:
        if rx.search(full): out.update({"chag", "chag:" + i})
    # tanach: explicit book reference, or a category named exactly as the book
    exact = {p.strip() for p in path_titles}
    for b, rx in BOOKS:
        if rx.search(full) or (b in exact and b not in ("רות", "אסתר", "שבת")):
            out.update({"tanach", "tanach:" + b})
    if w('תנ"ך', 'התנ"ך', "נביאים", "כתובים", "נ\"ך").search(full): out.add("tanach")
    is_mishna_only = "mishna" in out and not GEMARA.search(full)
    for m, rx in MASECHET:
        if is_mishna_only: break
        if rx.search(full) or ("מסכת " + m) in exact:
            out.update({"gemara", "gemara:" + ("נדה" if m == "נידה" else m)})
    if GEMARA.search(full): out.add("gemara")
    if TANYA.search(full): out.update({"chasidut", "chasidut:tanya"})
    # avoid the channel name "ישיבת אורות שאול" ever counting as Rav Kook's "אורות"
    return sorted(out)
